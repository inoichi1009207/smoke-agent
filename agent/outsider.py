def relation_sentences(node: dict[str, Any]) -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for leaf in member_leaves(node):
        text = " ".join(str(leaf.get("description") or "").split())
        for sentence in RELATION_SENTENCE.split(text):
            nouns = [m.span() for m in RELATION_NOUN.finditer(sentence)]
            verbs = [m.span() for m in RELATION_VERB.finditer(sentence)]
            if any(max(n0, v0) - min(n1, v1) <= RELATION_NEAR for n0, n1 in nouns for v0, v1 in verbs):
                found.append((str(leaf.get("id") or node.get("id")), sentence[:240]))
    return found

