def _signin_form_checked(body: str, page: str, at: int) -> bool:
    p = re.escape(page)
    loads = list(re.finditer(_PAGE_LOAD_STEP.format(p=p), body[:at]))
    if not loads:
        return bool(_SIGNIN_FORM_EVIDENCE.search(body))
    on_page = re.compile(r"(?<![\w$])" + p + r"(?![\w$])")

    for statement in re.split(r";|\n(?!\s*\.)", body[loads[-1].end():]):
        if on_page.search(statement) and _SIGNIN_FORM_EVIDENCE.search(statement):
            return True
    return False

