def typed_despite_limit(spec_text: str, node: dict[str, Any]) -> list[tuple[str, str, str, str]]:
    found: list[tuple[str, str, str, str]] = []
    for title, text, code in _test_blocks(spec_text, node):
        limits = [s.strip() for s in LIMIT_SENTENCE.findall(text) if LIMIT_TYPING.search(s) or LIMIT_ANY_FIELD.search(s)]
        if not limits:
            continue
        calls = _calls(code)
        for index, (_pos, verb, args) in enumerate(calls):
            if verb != "click" or not args or index == 0 or calls[index - 1][1] != "fill":
                continue
            _role, name, _ident = _target(args[0])
            if not name or len(name) < 3:
                continue
            for sentence in limits:
                if not _phrase_in(name, sentence):
                    continue
                label = _target(calls[index - 1][2][0])[1] if calls[index - 1][2] else None
                thing = re.search(r"\brequir\w*\s+(?:the\s+|a\s+|an\s+)?([\w\s-]{3,40}?)\s+to\s+be\b", sentence, re.IGNORECASE)
                words = {w.lower() for w in re.findall(r"[A-Za-z]{3,}", thing.group(1))} if thing else set()
                label_words = {w.lower() for w in re.findall(r"[A-Za-z]{3,}", label or "")}
                if LIMIT_ANY_FIELD.search(sentence) or (words & label_words):
                    fill = f"fill(page, {', '.join(a.strip() for a in calls[index - 1][2][:2])})"
                    found.append((title, fill, name, sentence[:240]))
                    break
    return list(dict.fromkeys(found))

