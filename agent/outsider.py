def _spec_tests(spec_text: str) -> list[tuple[str, str]]:
    code = re.sub(r"/\*.*?\*/", " ", spec_text, flags=re.S)
    code = re.sub(r"(?m)(^|[;{}]\s*|\s)//[^\n]*", r"\1", code)
    helpers: dict[str, tuple[list[str], str]] = {}
    for m in re.finditer(r"(?:async\s+)?function\s+(\w+)\s*\(([^)]*)\)\s*\{|(?:const|let)\s+(\w+)\s*=\s*async\s*\(([^)]*)\)\s*=>\s*\{", code):
        depth, i = 1, m.end()
        while i < len(code) and depth:
            depth += {"{": 1, "}": -1}.get(code[i], 0)
            i += 1
        params = [p.strip().split("=")[0].strip() for p in (m.group(2) if m.group(1) else m.group(4) or "").split(",")]

        body = re.sub(r"([{,]\s*)name(\s*[,}])", r"\1name: name\2", code[m.end(): i - 1])
        helpers[m.group(1) or m.group(3)] = (params, body)

    def call(c: re.Match) -> str:
        params, body = helpers[c.group(1)]
        args = [a.strip() for a in re.split(r",(?![^()]*\))", c.group(2))]
        for param, arg in zip(params, args):
            if param and re.fullmatch(r"[A-Za-z_$][\w$]*", param) and re.fullmatch(r"""(["'`])[^"'`\n$]{0,80}\1""", arg):
                body = re.sub(r"(?<![\w$.\"'`])" + re.escape(param) + r"(?![\w$\"'`])(?!\s*:)", lambda _m: arg, body)
        return " " + body + " "

    def expand(text: str) -> str:

        return re.sub(r"(?<!function )\b(" + "|".join(map(re.escape, helpers)) + r")\s*\(([^()\n]*)\)", call, text) if helpers else text
    heads = list(re.finditer(r"""\btest\(\s*(["'`])(.+?)\1""", code))
    out: list[tuple[str, str]] = []
    for index, head in enumerate(heads):

        arrow = code.find("=>", head.end())
        nxt = heads[index + 1].start() if index + 1 < len(heads) else len(code)
        start = code.find("{", arrow) if 0 <= arrow < nxt else -1
        if start < 0:
            continue
        depth, end = 0, start
        for end in range(start, len(code)):
            depth += {"{": 1, "}": -1}.get(code[end], 0)
            if depth == 0:
                break
        out.append((head.group(2), expand(code[start: end + 1])))
    return out

def _spec_steps(body: str, consts: dict[str, str] | None = None) -> list[dict[str, Any]]:
    consts = {**(consts or {}), **{m.group(1): m.group(3) for m in _CONST.finditer(body)}}
    steps: list[dict[str, Any]] = []
    for m in _STEP_CALL.finditer(body):
        name, role = m.group("name"), None
        if m.group("ident"):
            name = consts.get(m.group("ident"))
        if m.group("obj"):
            nm = re.search(r"""\bname\s*:\s*(?:["'`]([^"'`\n]{1,80})["'`]|([A-Za-z_$][\w$]*))""", m.group("obj"))
            rm = re.search(r"""\brole\s*:\s*["'`](\w+)["'`]""", m.group("obj"))
            name = (nm.group(1) or consts.get(nm.group(2) or "")) if nm else None
            role = rm.group(1) if rm else None
        elif m.group("alts"):
            alts = re.findall(r"""["'`]([^"'`\n]{1,80})["'`]""", m.group("alts"))
            name = alts[0] if alts else None
        steps.append({"verb": m.group("verb"), "name": name, "role": role, "at": m.start()})
    for m in _GOTO.finditer(body):
        steps.append({"verb": "goto", "name": m.group("url"), "role": None, "at": m.start()})
    for m in _RELOAD.finditer(body):
        steps.append({"verb": "reload", "name": None, "role": None, "at": m.start()})
    return sorted(steps, key=lambda s: s["at"])

def _scenario_table(node: dict[str, Any]) -> dict[str, tuple[dict[str, Any], dict[str, Any]]]:
    out: dict[str, tuple[dict[str, Any], dict[str, Any]]] = {}
    for leaf in member_leaves(node) or [node]:
        for scenario in leaf.get("scenarios") or []:
            if isinstance(scenario, dict) and str(scenario.get("name") or "").strip():
                out.setdefault(" ".join(str(scenario["name"]).split()).lower(), (leaf, scenario))
    return out

def _match_scenario(title: str, table: dict[str, Any]) -> Any:
    title = " ".join(title.split()).lower()

    return table.get(title) or next((v for name, v in table.items()
                                     if name and title.startswith(name) and not title[len(name):len(name) + 1].isalnum()), None)

