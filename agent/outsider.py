def sampled_lists(spec_text: str, node: dict[str, Any]) -> list[tuple[list[str], list[str], str]]:
    texts = [str(node.get("description") or "")]
    for scenario in node.get("scenarios") or []:
        texts += [str(step.get("content") or "") for step in scenario.get("steps") or []
                  if str(step.get("keyword") or "").strip().upper() not in ("GIVEN", "AND GIVEN")]
    code = _code_only(spec_text).lower()

    _entries, seeds = _stated_names(_whole_requirement(node))
    seeds = seeds | {v.strip().lower() for v in re.findall(r"`([^`\n]{1,80})`", str(node.get("seed_sentences") or ""))}
    found: list[tuple[list[str], list[str], str]] = []
    seen: set[tuple[str, ...]] = set()
    for text in texts:
        for sentence in re.split(r"(?<=[.!?;])\s+(?=[A-Z(])", " ".join(text.split())):
            if DATA_SENTENCE.search(sentence):
                continue

            for enum in LIST_RUN.finditer(sentence):
                if not LIST_LEAD.search(sentence[max(0, enum.start() - 50):enum.start()]):
                    continue
                items = list(dict.fromkeys(q.strip() for q in LIST_ITEM.findall(enum.group(0))
                                           if q.strip() and "<" not in q and q.strip().lower() not in seeds))
                if len(items) < 3 or tuple(items) in seen:
                    continue
                seen.add(tuple(items))
                missing = [item for item in items if item.lower() not in code]
                if missing and len(missing) < len(items):
                    found.append((items, missing, sentence))
    return found

SPEC_ROLE_PAIR = re.compile(r"""\{\s*role\s*:\s*["'](?P<role>\w+)["']\s*,\s*name\s*:\s*["'`](?P<name>[^"'`\n$]{1,80})["'`]\s*\}""")
PLACEHOLDER_FILLER = {"current", "new", "old", "selected", "default", "the", "a", "an", "its", "their", "name", "names",
                      "value", "title", "label", "text", "id", "of", "target", "given", "chosen", "active"}

def untemplated_names(spec_text: str, node: dict[str, Any]) -> list[tuple[str, str, str, str]]:
    whole = _whole_requirement(node)
    entries, _seeds = _stated_names(whole)
    stated_names = {name.lower() for name, _roles in entries}
    templates: dict[str, list[tuple[str, re.Pattern[str], set[str]]]] = {}
    for name, roles in entries:
        literal = re.sub(r"<[^<>]+>|\s", "", name)
        holders = re.findall(r"<([^<>]+)>", name)
        if not holders or len(literal) < 3:
            continue
        nouns = {w for h in holders for w in re.findall(r"[a-z]+", h.lower()) if w not in PLACEHOLDER_FILLER and len(w) > 2}
        shape = re.compile(re.sub(r"<[^<>]+>", ".+", re.escape(name).replace(r"\<", "<").replace(r"\>", ">")), re.IGNORECASE)
        for role in roles:
            templates.setdefault(role, []).append((name, shape, nouns))
    if not templates:
        return []
    flat = " ".join(whole.split())
    all_shapes = [shape for group in templates.values() for _, shape, _ in group]
    found: list[tuple[str, str, str, str]] = []
    for m in SPEC_ROLE_PAIR.finditer(_code_only(spec_text)):
        role, value = m.group("role").lower(), m.group("name").strip()

        if role not in templates or value.lower() in stated_names or any(s.fullmatch(value) for s in all_shapes):
            continue
        for template, _shape, nouns in templates[role]:
            words = {w.lower() for w in re.findall(r"[A-Za-z]{3,}", re.sub(r"<[^<>]+>", " ", template))}
            if not nouns or words & {w.lower() for w in re.findall(r"[A-Za-z]{3,}", value)}:
                continue

            noun = r"\b(?:" + "|".join(map(re.escape, sorted(nouns))) + r")(?:e?s)?\b"
            after = re.compile(noun + r"\s+(?:(?:named|called)\s+)?(" + _LIST_Q + r"(?:(?:\s*,\s*(?:and\s+|or\s+)?|\s+(?:and|or)\s+)"
                               + _LIST_Q + r")*)", re.IGNORECASE)
            listed = {q.strip().lower() for run in after.finditer(flat) for q in LIST_ITEM.findall(run.group(1))}
            before = re.search(r"[`\"“]" + re.escape(value) + r"[`\"”]\s+" + noun, flat, re.IGNORECASE)
            if value.lower() in listed or before:
                filled = re.sub(r"<[^<>]+>", lambda _m: value, template, count=1)
                found.append((role, value, template, filled))
                break
    return list(dict.fromkeys(found))

TEST_START = re.compile(r"\n\s*test(?:\.\w+)?\(")
REQ_ID = re.compile(r"REQ-\d+(?:[.-]\d+)*")
HELPER_CALL = re.compile(r"(?<![\w$.])(?P<verb>click|doubleClick|rightClick|fill|check|choose|hover|press|see|notSee|seeOnce|"
                         r"upload|download|drag|locateAll|locate)\(\s*page\s*,\s*")

def _sections(node: dict[str, Any]) -> dict[str, str]:
    leaves = [leaf for leaf in node.get("_leaves") or [] if isinstance(leaf, dict)]
    if leaves:
        return {str(leaf.get("id")): describe_node(leaf) for leaf in leaves}
    text = describe_node(node)
    found = {m.group(1): m.group(2) for m in re.finditer(r"###\s+(REQ-\d+(?:[.-]\d+)*)[^\n]*\n(.*?)(?=\n###\s+REQ-|\Z)", text, re.S)}
    return found or {str(node.get("id")): text}

def _test_blocks(spec_text: str, node: dict[str, Any]) -> list[tuple[str, str, str]]:
    sections = _sections(node)
    blocks: list[tuple[str, str, str]] = []
    for block in TEST_START.split("\n" + spec_text)[1:]:
        title_match = re.match(r"""\s*(["'`])((?:(?!\1)[^\n\\]|\\.)*)\1""", block)
        title = title_match.group(2) if title_match else ""
        ids = [i for i in dict.fromkeys(REQ_ID.findall(title))]
        own = [sections.get(i) or sections.get(i.replace(".", "-")) for i in ids]
        own = [s for s in own if s]
        if not own and len(sections) == 1:
            own = list(sections.values())
        if not own:
            continue
        code = _code_only(block[title_match.end():] if title_match else block)
        blocks.append((title, " ".join("\n".join(own).split()), code))
    return blocks

def _target(argument: str) -> tuple[str | None, str | None, str | None]:
    argument = argument.strip()
    if argument.startswith("{"):
        role = re.search(r"""\brole\s*:\s*["'`](\w+)["'`]""", argument)
        literal = re.search(r"""\bname\s*:\s*["'`]([^"'`\n]{1,80})["'`]""", argument)
        ident = re.search(r"""\bname\s*:\s*([A-Za-z_$][\w$]*)""", argument)
        return (role.group(1) if role else None, literal.group(1) if literal else None, ident.group(1) if ident and not literal else None)
    literal = re.fullmatch(r"""["'`]([^"'`\n]{1,80})["'`]""", argument)
    if literal:
        return None, literal.group(1), None
    ident = re.fullmatch(r"[A-Za-z_$][\w$]*", argument)
    return None, None, ident.group(0) if ident else None

def _calls(code: str) -> list[tuple[int, str, list[str]]]:
    found = []
    for m in HELPER_CALL.finditer(code):
        args = call_args(code, code.index("(", m.start()))
        found.append((m.start(), m.group("verb"), args[1:]))
    return found

def _phrase_in(name: str, text: str) -> bool:
    return bool(re.search(r"(?<![\w-])" + r"\s+".join(map(re.escape, name.split())) + r"(?![\w-])", text, re.IGNORECASE))

