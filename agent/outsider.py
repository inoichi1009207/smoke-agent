def _mask_js(text: str) -> str:
    out = list(text)
    i, n = 0, len(text)
    last = ""
    while i < n:
        c = text[i]
        if c == "/" and text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out[i:j] = " " * (j - i)
            i = j
            continue
        if c == "/" and text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out[i:j] = ["\n" if ch == "\n" else " " for ch in text[i:j]]
            i = j
            continue
        if c in "\"'`" or (c == "/" and (not last or last in "(,=:[!&|?{};+-*%<>~^")):
            j = i + 1
            in_class = False
            while j < n:
                ch = text[j]
                if ch == "\\":
                    j += 2
                    continue
                if c != "`" and ch == "\n":
                    break
                if c == "/" and ch == "[":
                    in_class = True
                elif c == "/" and ch == "]":
                    in_class = False
                elif ch == c and not in_class:
                    break
                j += 1
            j = min(j, n - 1)
            for k in range(i + 1, j):
                out[k] = "\n" if text[k] == "\n" else "_"
            i = j + 1
            last = "_"
            continue
        if not c.isspace():
            last = c
        i += 1
    return "".join(out)

def _arg_spans(masked: str, open_at: int) -> tuple[list[tuple[int, int]], int]:
    depth, start, spans = 0, open_at + 1, []
    for k in range(open_at, len(masked)):
        ch = masked[k]
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
            if depth == 0:
                if masked[start:k].strip():
                    spans.append((start, k))
                return spans, k
        elif ch == "," and depth == 1:
            spans.append((start, k))
            start = k + 1
    return spans, len(masked)

