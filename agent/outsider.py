def _mentions(name: str, role: str, flat: str) -> tuple[bool, bool]:
    role_words = [w for w, r in ROLE_WORDS.items() if r == role]
    role_re = re.compile(r"\b(?:" + "|".join(map(re.escape, role_words)) + r")\b"
                         + ("|" + ROLE_PHRASES[role] if role in ROLE_PHRASES else ""), re.IGNORECASE)
    other, silent = False, False
    for m in re.finditer(r"[`\"“]" + re.escape(name) + r"[`\"”]", flat, re.IGNORECASE):
        start, end = _clause_span(flat, m.start(), m.end())
        if role_re.search(flat[start:end]):
            continue
        before = [w.lower() for w in re.findall(r"[A-Za-z]+", flat[max(start, m.start() - 60):m.start()])]
        while before and before[-1] in SKIP_BEFORE:
            before.pop()
        after = re.match(r"\s*([A-Za-z]+)", flat[m.end():end])
        if (before and before[-1] in OTHER_THING) or (after and after.group(1).lower() in OTHER_THING):
            other = True
        else:
            silent = True
    return other, silent

def _clause_span(text: str, start: int, end: int) -> tuple[int, int]:
    left = max(text.rfind(c, 0, start) for c in ".;:!?")
    rights = [i for i in (text.find(c, end) for c in ".;!?") if i != -1]
    return left + 1, min(rights) if rights else len(text)

def bare_stated_controls(spec_text: str, node: dict[str, Any]) -> list[tuple[str, str, str]]:
    whole = _whole_requirement(node)
    entries, seeds = _stated_names(whole)
    single = {name.lower(): (name, roles[0]) for name, roles in entries if len(roles) == 1 and "<" not in name}
    flat = " ".join(whole.split())
    found: list[tuple[str, str, str]] = []
    for m in BARE_TARGET.finditer(_code_only(spec_text)):
        verb, key = m.group("verb"), m.group("name").strip().lower()
        if key not in single or key in seeds:
            continue
        name, role = single[key]
        if verb not in LOOKING_VERBS and role not in BARE_VERB_ROLES.get(verb, set()):
            continue
        other, silent = _mentions(name, role, flat)
        if other or (verb in LOOKING_VERBS and silent):
            continue
        found.append((verb, name, role))
    return list(dict.fromkeys(found))

