def unstated_control_names(spec_text: str, node: dict[str, Any]) -> list[tuple[str, list[str]]]:
    flat = " ".join(requirement_text(node).split())
    quotes = list(dict.fromkeys(m.group(1).strip() for m in QUOTED_NAME.finditer(flat)))
    templates = [re.compile(re.sub(r"<[^>]+>", ".+", re.escape(q).replace(r"\<", "<").replace(r"\>", ">")), re.IGNORECASE)
                 for q in quotes if "<" in q and ">" in q and len(re.sub(r"<[^>]+>|\s", "", q)) >= 3]
    names = [q for q in quotes if "<" not in q]
    typed = {m.lower() for m in re.findall(r"""\bfill\(\s*page\s*,\s*[^,\n]+,\s*["'`]([^"'`\n]{2,80})["'`]""", spec_text)}

    written = CONTROL_TARGET.sub(" ", INV_LOOKING.sub(" ", spec_text))
    typed |= {s.lower() for s in re.findall(r"""["'`]([^"'`\n]{2,160})["'`]""", written)}

    def words(text: str) -> set[str]:
        return {w for w in re.findall(r"[a-z0-9]+", text.lower()) if len(w) > 2 and w not in NAME_FILLER}

    found: dict[str, list[str]] = {}
    for m in CONTROL_TARGET.finditer(spec_text):
        name = m.group("name").strip()
        if name in found or any(name.lower() in t for t in typed) or re.fullmatch(r"[A-Z]{1,3}[0-9]{1,5}", name):
            continue
        if re.search(r"(?<![\w])" + re.escape(name) + r"(?![\w])", flat, re.IGNORECASE):
            continue
        if any(template.fullmatch(name) for template in templates):
            continue
        mine = words(name)
        near = sorted((q for q in names if words(q) & mine), key=lambda q: -len(words(q) & mine))
        if near:
            found[name] = near[:6]
    return list(found.items())

