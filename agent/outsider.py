def helper_typed_calls(spec_text: str) -> list[tuple[int, str]]:
    consts = {m.group("var"): m.group("value") for m in INV_CONST.finditer(spec_text)}
    helpers: dict[str, set[int]] = {}
    for m in INV_HELPER.finditer(spec_text):
        params = [x.strip() for x in m.group("params").split(",")]
        body = spec_text[m.end():m.end() + 1500]
        body = body[:body.find("\n}")] if "\n}" in body else body
        indexes = {params.index(p.group("param")) for p in HELPER_TYPES_PARAM.finditer(body) if p.group("param") in params[1:]}
        if indexes:
            helpers[m.group("name") or m.group("arrow")] = indexes
    calls: list[tuple[int, str]] = []
    if not helpers:
        return calls
    for m in re.finditer(r"(?<![\w$.])(" + "|".join(map(re.escape, helpers)) + r")\(", spec_text):
        args = call_args(spec_text, m.end() - 1)
        for index in sorted(helpers[m.group(1)]):
            arg = args[index].strip() if index < len(args) else ""
            if arg[:1] in ("\"", "'", "`") and arg[-1:] == arg[:1] and "$" not in arg and len(arg) >= 2:
                value = arg[1:-1]
            else:
                value = consts.get(arg, "")
            if value:
                calls.append((m.start(), value))
    return calls

def helper_typed_values(spec_text: str) -> set[str]:
    return {value for _position, value in helper_typed_calls(spec_text)}

TEST_CALL = re.compile(r"(?m)^[ \t]*test(?:\.\w+)?\(")

def _test_span(spec_text: str, position: int) -> tuple[int, int] | None:
    starts = [m.start() for m in TEST_CALL.finditer(spec_text)]
    for i, start in enumerate(starts):
        end = starts[i + 1] if i + 1 < len(starts) else len(spec_text)
        if start <= position < end:
            return start, end
    return None

def invented_records(spec_text: str, node: dict[str, Any]) -> list[str]:
    requirement = requirement_text(node).lower()
    consts = {m.group("var"): m.group("value") for m in INV_CONST.finditer(spec_text)}
    typed = {str(m.group("value") or consts.get(m.group("ref") or "", "")).lower() for m in INV_TYPED.finditer(spec_text)} - {""}

    helper_calls = helper_typed_calls(spec_text) if batch_boilerplate(node) else []

    def made(low: str, position: int, both_ways: bool) -> bool:
        span = _test_span(spec_text, position) if helper_calls else None
        if span is None:
            return False
        before = {value.lower() for at, value in helper_calls if span[0] <= at < position}
        return any(low in t or (both_ways and t in low) for t in before)

    found: list[str] = []

    def stated(low: str) -> bool:

        parts = [part.strip() for part in low.split("/") if part.strip()]
        return low in requirement or (len(parts) > 1 and all(part in requirement for part in parts))

    for m in INV_LOOKUP.finditer(spec_text):
        name = consts.get(m.group("ref") or "") if not m.group("value") else ""
        low = (name or "").lower().strip()
        if not low or stated(low) or any(low in t or t in low for t in typed) or made(low, m.start(), True):
            continue
        found.append(name)

    patterns = []
    for quoted in re.findall(r"[`“\"]([^`”\"\n]{3,80})[`”\"]", requirement_text(node)):

        if "<" in quoted and ">" in quoted and len(re.sub(r"<[^>]+>|\s", "", quoted)) >= 3:
            patterns.append(re.compile("^" + re.sub(r"<[^>]+>", ".+", re.escape(quoted).replace(r"\<", "<").replace(r"\>", ">")) + "$", re.I))

    others = {s.lower() for s in re.findall(r"""["'`]([^"'`\n]{2,160})["'`]""", INV_LOOKING.sub(" ", spec_text))}
    for m in INV_INLINE.finditer(spec_text):
        name = m.group("value").strip()
        low = name.lower()

        if (stated(low) or any(low in t for t in typed | others) or made(low, m.start(), False)
                or re.fullmatch(r"[A-Z]{1,3}[0-9]{1,5}", name) or any(p.match(name) for p in patterns)):
            continue
        found.append(name)
    return list(dict.fromkeys(found))

