def dialog_controls(text: str) -> dict[str, str]:
    places: dict[str, set[str]] = {}
    for sentence in re.split(r"(?<=[.!?])\s+|\n+", text):
        dialogs = {a or b for a, b in DIALOG_NAMED.findall(sentence)}
        names = set(re.findall(QUOTED, sentence)) - dialogs
        if len(dialogs) == 1:

            dialog = next(iter(dialogs))
            mention = DIALOG_NAMED.search(sentence)
            verb = CONTAINS.search(sentence, mention.end())
            inside = set(re.findall(QUOTED, sentence[verb.end():])) if verb else set()
            for clause in re.split(r"[,;:]", sentence):
                if re.search(r"\b(?:in|inside|within)\s+the\s+" + QUOTED + r"\s+dialog\b", clause, re.IGNORECASE):
                    inside |= set(re.findall(QUOTED, clause))
            for name in (inside & names) - {dialog}:
                places.setdefault(name, set()).add(dialog)

        for clause in re.split(r"[,;:]", sentence):
            if OTHER_CONTAINER.search(clause) and not DIALOG_NAMED.search(clause):
                for name in set(re.findall(QUOTED, clause)):
                    places.setdefault(name, set()).add("")
    return {name: next(iter(where)) for name, where in places.items() if len(where) == 1 and "" not in where}

def call_args(text: str, start: int) -> list[str]:
    depth, current, args = 0, "", []
    for char in text[start:]:
        if char in "([{":
            depth += 1
            if depth == 1:
                continue
        if char in ")]}":
            depth -= 1
            if depth == 0:
                args.append(current.strip())
                return args
        if char == "," and depth == 1:
            args.append(current.strip())
            current = ""
            continue
        current += char
    return args

def unscoped_dialog_controls(spec_text: str, node: dict[str, Any]) -> list[tuple[str, str]]:
    placed = dialog_controls(describe_node(node) + "\n" + str(node.get("reference_requirements") or ""))
    own = set(re.findall(QUOTED, describe_node(node)))
    later = set(node.get("later_names") or [])

    scopes = {m.group(1): (m.group(2), m.group(3) or "") for m in re.finditer(
        r"""(?:const|let|var)\s+(\w+)\s*=\s*region\(\s*page\s*,\s*["'`](\w+)["'`]\s*(?:,\s*["'`]([^"'`\n]{1,60})["'`])?\s*\)""", spec_text)}
    found: list[tuple[str, str]] = []
    for match in SCOPED_CALL.finditer(spec_text):
        args = call_args(spec_text, spec_text.index("(", match.start()))

        name = re.search(r"name:\s*[\"'`]([^\"'`\n]{1,60})[\"'`]", args[1]) if len(args) >= 2 else None
        name = name or (re.match(r"\s*[\"'`]([^\"'`\n]{1,60})[\"'`]", args[1]) if len(args) >= 2 else None)
        if not (name and name.group(1) in placed and name.group(1) in own):
            continue
        dialog = placed[name.group(1)]
        if dialog in later:

            continue
        if len(args) <= BASE_ARGS[match.group(1)]:
            found.append((name.group(1), dialog))
            continue

        scope = args[-1].strip()
        role, scope_name = scopes.get(scope, ("", ""))
        inline = re.match(r"""region\(\s*page\s*,\s*["'`](\w+)["'`]\s*(?:,\s*["'`]([^"'`\n]{1,60})["'`])?\s*\)""", scope)
        if inline:
            role, scope_name = inline.group(1), inline.group(2) or ""
        if role == "dialog" and scope_name != dialog:
            found.append((name.group(1), dialog))
    return list(dict.fromkeys(found))

