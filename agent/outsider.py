def review_acceptance(llm: LLM, node: dict[str, Any], spec: AuthoredFile, prefix: str, log=print) -> str:
    generated = review_boilerplate_note(node)
    relations = review_relation_note(node, prefix)
    review_messages = [
        {"role": "system", "content": REVIEW_PROMPT},
        {"role": "user", "content": reference_block(node) + f"{describe_node(node)}\n\n" + (f"{generated}\n" if generated else "")
         + (f"{relations}\n" if relations else "")
         + f"The acceptance spec:\n{spec.content}\n\nCheck it now."},
    ]
    message = llm.chat(
        review_messages,
        max_tokens=4000,
        tag=f"outsider:{prefix}:review",
        thinking=True,
    )
    answer = str(message.get("content") or "").strip()

    from .settings import setting_on as _review_retry_setting_on
    if (not answer and getattr(llm, "last_finish_reason", "") == "length"
            and _review_retry_setting_on("outsider_review_retry", True)):
        log(f"[outsider] {prefix}: review answer empty at the length limit (max_tokens=4000); "
            "retrying once with max_tokens=12000")
        message = llm.chat(
            review_messages,
            max_tokens=12000,
            tag=f"outsider:{prefix}:review-retry",
            thinking=True,
        )
        answer = str(message.get("content") or "").strip()
    problems = [line.strip() for line in answer.splitlines() if line.strip().upper().startswith("PROBLEM:")]

    def norm(text: str) -> str:
        return re.sub(r"\s+", " ", str(text).translate(REVIEW_QUOTE_FOLD)).strip().lower()

    requirement = norm(requirement_text(node))
    script = norm(spec.content)
    kept, dropped, generated_claims = [], 0, 0
    for line in problems:
        quote = re.search(r"requirement:\s*[\"“](.+?)[\"”]\s*\|", line, re.IGNORECASE)
        spec_quote = re.search(r"spec:\s*[\"“](.+?)[\"”]\s*(?:\||$)", line, re.IGNORECASE)
        quoted_line = norm(spec_quote.group(1).replace('\\"', '"').replace("\\'", "'")) if spec_quote else ""

        said = norm(quote.group(1).replace('\\"', '"').replace("\\'", "'")) if quote else ""
        why = ("no quoted requirement" if not quote
               else "requirement quote shorter than six words" if len(said.split()) < 6
               else "requirement quote not in the requirement" if said not in requirement
               else "quoted spec line not in the spec" if quoted_line and quoted_line not in script
               else "")
        if not why:

            if quotes_only_boilerplate(quote.group(1), node):
                generated_claims += 1
                log(f"[outsider] {prefix}: review claim dropped (it quotes only a generated boilerplate scenario): {line[:300]}")
                continue
            kept.append(line)
        else:
            dropped += 1
            log(f"[outsider] {prefix}: review claim dropped ({why}): {line[:300]}")
    if not answer:
        log(f"[outsider] {prefix}: review inconclusive (empty answer); the spec stays as written")
    else:
        log(f"[outsider] {prefix}: review -> " + (f"{len(kept)} problem(s): {kept[0][:200]}" if kept else "OK")
            + (f"; {dropped} claim(s) dropped: their quote is not in the requirement" if dropped else "")
            + (f"; {generated_claims} claim(s) dropped: they quote only a generated boilerplate scenario" if generated_claims else ""))

    return "\n".join((kept + deterministic_review(node, spec, prefix, log=log, ledger_hint=False))[:8]
                     + coverage_problems(node, spec, prefix, log=log))

