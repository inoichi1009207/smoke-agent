def option_entries_not_as_options(spec_text: str, node: dict[str, Any]) -> list[tuple[str, str, str, str]]:
    flat = " ".join(requirement_text(node).split())
    found: list[tuple[str, str, str]] = []
    for title, text, code in _test_blocks(spec_text, node):
        kinds: set[str] = set()
        sentence = ""
        for m in OPTION_ENTRY.finditer(text):
            words = [m.group("kind") or ""] + re.findall(r"\b([a-z]+)(?:'s)?\s+(?:user)?names?\b", m.group("tail") or m.group("tail2") or "")
            new = {w.lower() for w in words if w and w.lower() not in OPTION_FILLER and len(w) > 2}
            if new and not sentence:
                start = max(text.rfind(". ", 0, m.start()) + 2, 0)
                sentence = text[start:m.end()].strip()
            kinds |= new
        if not kinds:
            continue
        values: set[str] = set()
        for kind in kinds:
            for run in re.finditer(r"\b" + re.escape(kind) + r"s?\s+((?:" + _LIST_Q + r"(?:\s*,\s*(?:and\s+|or\s+)?|\s+(?:and|or)\s+)?)+)", flat, re.IGNORECASE):
                values |= {q.strip() for q in LIST_ITEM.findall(run.group(1)) if q.strip()}
        calls = _calls(code)
        for index, (_pos, verb, args) in enumerate(calls):
            if verb not in ("click", "check", "doubleClick") or not args:
                continue
            role, literal, ident = _target(args[0])
            if role == "option":
                continue
            previous = calls[index - 1] if index else None
            typed_before = bool(previous and previous[1] == "fill" and len(previous[2]) >= 2
                                and previous[2][1].strip() == args[0].strip() and (literal or ident))
            if (literal and literal in values) or typed_before:
                what = (literal and f'"{literal}"') or ident
                call = f"{verb}(page, {args[0].strip()})"
                found.append((title, call, f'{{ role: "option", name: {what} }}', sentence[:200]))
    return list(dict.fromkeys(found))

CLOCK_CALL = re.compile(r"Date\.now\(\)|Math\.random\(\)|crypto\.randomUUID\(\)|performance\.now\(\)")
NEGATIVE_VALUE = re.compile(r"bad|invalid|wrong|malformed|illegal|reject|broken|unsafe", re.IGNORECASE)
GENERIC_FIELDS = {"name", "title", "value", "text", "search", "input", "field"}

def _string_parts(expression: str) -> str:
    parts = re.findall(r'"((?:\\.|[^"\\\n])*)"|\'((?:\\.|[^\'\\\n])*)\'', expression)
    text = "".join(a or b for a, b in parts)
    for template in re.findall(r"`((?:\\.|[^`\\])*)`", expression):
        text += re.sub(r"\$\{[^}]*\}", "", template)
    return text

def misformatted_generated_values(spec_text: str, node: dict[str, Any]) -> list[tuple[str, str, str, str]]:
    flat = " ".join(requirement_text(node).split())
    code_all = _code_only(spec_text)
    definitions = [(m.start(), m.group(1), m.group(2)) for m in
                   re.finditer(r"(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*([^;\n]+)", code_all)]
    found: list[tuple[str, str, str, str]] = []
    for _title, _text, code in _test_blocks(spec_text, node):
        for pos, verb, args in _calls(code):
            if verb != "fill" or len(args) < 2:
                continue
            _role, label, _ident = _target(args[0])
            value = args[1].strip()
            if not label or not re.fullmatch(r"[A-Za-z_$][\w$]*", value):
                continue
            if label.strip().lower() in GENERIC_FIELDS or NEGATIVE_VALUE.search(value):
                continue

            local = [m.group(1) for m in re.finditer(r"(?:const|let|var)\s+" + re.escape(value) + r"\s*=\s*([^;\n]+)", code[:pos])]
            module = [expr for _start, name, expr in definitions if name == value]
            expression = local[-1] if local else (module[0] if module else "")
            if not CLOCK_CALL.search(expression) or re.search(r"\.toLowerCase\s*\(", expression):
                continue
            literal = _string_parts(expression)
            if NEGATIVE_VALUE.search(literal):
                continue

            rest = code[pos + 1:]
            if not re.search(r"(?<![\w$.])(?:click|see|seeOnce|item|hover|locateAll|locate|doubleClick|fill)\(\s*page\s*,\s*(?:[^,()]*,\s*)?"
                             r"(?:\{[^}]*\bname\s*:\s*)?" + re.escape(value) + r"\b", rest):
                continue
            for m in re.finditer(r"(?<![\w-])" + r"\s+".join(map(re.escape, label.split())) + r"(?![\w-])", flat, re.IGNORECASE):
                end = [i for i in (flat.find(". ", m.end()), flat.find("; ", m.end())) if i != -1]
                window = flat[m.end():min(end + [m.end() + 250])][:250]
                lowercase = re.search(r"\blower-?case\b", window, re.IGNORECASE)
                only = re.search(r"\bonly\b|\bmust\b|\bconsists?\s+of\b", window, re.IGNORECASE)
                if not (lowercase and only):
                    continue
                broken = []
                if re.search(r"[A-Z]", literal) and not re.search(r"upper-?case|capital", window, re.IGNORECASE):
                    broken.append("upper-case letters")
                if re.search(r"\s", literal) and not re.search(r"\bspaces?\b|white-?space", window, re.IGNORECASE):
                    broken.append("spaces")
                if "_" in literal and not re.search(r"underscores?", window, re.IGNORECASE):
                    broken.append("underscores")
                if broken:
                    rule = window[:160].strip(" ,")
                    found.append((label, value, expression.strip(), ", ".join(broken) + f' -- the requirement: "{label} {rule}"'))
                    break
    return list(dict.fromkeys(found))

LIMIT_SENTENCE = re.compile(r"[^.;]*\b(?:without\s+requiring|(?:does|do)\s+not\s+require|(?:is|are)\s+not\s+required|"
                            r"no\s+need\s+to)\b[^.;]*", re.IGNORECASE)
