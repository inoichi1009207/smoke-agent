@lru_cache(maxsize=4)
def _stated_names(text: str) -> tuple[tuple[tuple[str, tuple[str, ...]], ...], frozenset[str]]:

    stated, seeds = extract_stated_controls(text, unquoted=False)
    roles: dict[str, set[str]] = {}
    spelled: dict[str, str] = {}
    for entry in stated:
        name = str(entry["name"]).strip()
        roles.setdefault(name.lower(), set()).update(entry["roles"])
        spelled.setdefault(name.lower(), name)
    return tuple((spelled[key], tuple(sorted(value))) for key, value in roles.items()), frozenset(seeds)

def _code_only(spec_text: str) -> str:
    code = re.sub(r"/\*.*?\*/", " ", spec_text, flags=re.S)
    code = re.sub(r"(?m)(^|[;{}]\s*|\s)//[^\n]*", r"\1", code)
    return re.sub(r"""\btest(?:\.\w+)?\(\s*(["'`])(?:(?!\1)[^\n\\]|\\.)*\1""", "test(", code)

